// ---------------------------------------------------------------- Linux
const HOME = os.homedir();
const XDG_DATA = process.env.XDG_DATA_HOME || path.join(HOME, '.local', 'share');
const XDG_CONFIG = process.env.XDG_CONFIG_HOME || path.join(HOME, '.config');
const LINUX = {
  dataDir: path.join(XDG_DATA, 'lanclip'),
  nautilus: path.join(XDG_DATA, 'nautilus', 'scripts'),
  caja: path.join(XDG_CONFIG, 'caja', 'scripts'),
  nemo: path.join(XDG_DATA, 'nemo', 'actions'),
  dolphin: path.join(XDG_DATA, 'kio', 'servicemenus'),
  thunar: path.join(XDG_CONFIG, 'Thunar', 'uca.xml'),
};
const THUNAR_BEGIN = '<!-- lanclip:begin -->';
const THUNAR_END = '<!-- lanclip:end -->';

function installLinux(launcher) {
  const cli = writeWrapper(LINUX.dataDir, launcher);
  const q = shQuote(cli);

  // Nautilus (GNOME) and Caja (MATE): Scripts submenu. Selected files arrive as arguments, cwd = current folder.
  for (const dir of [LINUX.nautilus, LINUX.caja]) {
    writeExecutable(path.join(dir, LABELS.send), `#!/bin/sh\n[ $# -gt 0 ] && exec ${q} --lanclip-send "$@"\n`);
    writeExecutable(path.join(dir, LABELS.paste), `#!/bin/sh\nd="$PWD"\n[ $# -eq 1 ] && [ -d "$1" ] && d="$1"\nexec ${q} --lanclip-paste "$d"\n`);
    writeExecutable(path.join(dir, LABELS.clip), `#!/bin/sh\nexec ${q} --lanclip-send-clipboard\n`);
  }

  // Nemo (Cinnamon)
  fs.mkdirSync(LINUX.nemo, { recursive: true });
  const nemo = (file, name, exec, selection, ext) => fs.writeFileSync(path.join(LINUX.nemo, file),
    `[Nemo Action]\nName=${name}\nComment=Lanclip\nExec=${exec}\nIcon-Name=edit-copy\nSelection=${selection}\nExtensions=${ext};\n`);
  nemo('lanclip-send.nemo_action', LABELS.send, `${cli} --lanclip-send %F`, 'notnone', 'any');
  nemo('lanclip-paste.nemo_action', LABELS.paste, `${cli} --lanclip-paste %P`, 'none', 'any');
  nemo('lanclip-paste-into.nemo_action', LABELS.paste, `${cli} --lanclip-paste %F`, 's', 'dir');
  nemo('lanclip-clip.nemo_action', LABELS.clip, `${cli} --lanclip-send-clipboard`, 'none', 'any');

  // Dolphin (KDE). Plasma 6 requires service menus to be executable.
  writeExecutable(path.join(LINUX.dolphin, 'lanclip-send.desktop'), `[Desktop Entry]
Type=Service
MimeType=all/allfiles;inode/directory;
X-KDE-ServiceTypes=KonqPopupMenu/Plugin
Actions=send;
X-KDE-Priority=TopLevel

[Desktop Action send]
Name=${LABELS.send}
Icon=edit-copy
Exec=${shQuote(cli)} --lanclip-send %F
`);
  writeExecutable(path.join(LINUX.dolphin, 'lanclip-paste.desktop'), `[Desktop Entry]
Type=Service
MimeType=inode/directory;
X-KDE-ServiceTypes=KonqPopupMenu/Plugin
Actions=paste;clip;
X-KDE-Priority=TopLevel

[Desktop Action paste]
Name=${LABELS.paste}
Icon=edit-paste
Exec=${shQuote(cli)} --lanclip-paste %f

[Desktop Action clip]
Name=${LABELS.clip}
Icon=edit-copy
Exec=${shQuote(cli)} --lanclip-send-clipboard
`);

  // Thunar (XFCE): merge our actions into uca.xml between markers.
  const action = (name, icon, cmd, patterns, kinds) => `<action>
  <icon>${icon}</icon><name>${xml(name)}</name><submenu></submenu>
  <unique-id>lanclip-${name.replace(/\W+/g, '-').toLowerCase()}</unique-id>
  <command>${xml(cmd)}</command><description>Lanclip</description>
  <range></range><patterns>${patterns}</patterns>${kinds}
</action>`;
  const block = [
    THUNAR_BEGIN,
    action(LABELS.send, 'edit-copy', `${shQuote(cli)} --lanclip-send %F`, '*', '<directories/><audio-files/><image-files/><other-files/><text-files/><video-files/>'),
    action(LABELS.paste, 'edit-paste', `${shQuote(cli)} --lanclip-paste %f`, '*', '<directories/>'),
    THUNAR_END,
  ].join('\n');
  let uca = '<?xml version="1.0" encoding="UTF-8"?>\n<actions>\n</actions>\n';
  try { uca = fs.readFileSync(LINUX.thunar, 'utf8'); } catch {}
  uca = stripThunar(uca).replace(/<\/actions>\s*$/, `${block}\n</actions>\n`);
  fs.mkdirSync(path.dirname(LINUX.thunar), { recursive: true });
  fs.writeFileSync(LINUX.thunar, uca);
}

function stripThunar(text) {
  const a = text.indexOf(THUNAR_BEGIN), b = text.indexOf(THUNAR_END);
  return a >= 0 && b > a ? text.slice(0, a) + text.slice(b + THUNAR_END.length).replace(/^\n/, '') : text;
}

function uninstallLinux() {
  for (const dir of [LINUX.nautilus, LINUX.caja]) {
    for (const name of [LABELS.send, LABELS.paste, LABELS.clip]) fs.rmSync(path.join(dir, name), { force: true });
  }
  for (const f of ['lanclip-send', 'lanclip-paste', 'lanclip-paste-into', 'lanclip-clip']) fs.rmSync(path.join(LINUX.nemo, `${f}.nemo_action`), { force: true });
  for (const f of ['lanclip-send', 'lanclip-paste']) fs.rmSync(path.join(LINUX.dolphin, `${f}.desktop`), { force: true });
  try { fs.writeFileSync(LINUX.thunar, stripThunar(fs.readFileSync(LINUX.thunar, 'utf8'))); } catch {}
  fs.rmSync(path.join(LINUX.dataDir, 'lanclip-cli.sh'), { force: true });
}

// ---------------------------------------------------------------- autostart (Linux; Win/mac use Electron's login items)
const AUTOSTART = path.join(XDG_CONFIG, 'autostart', 'lanclip.desktop');
function setLinuxAutostart(enabled, launcher) {
  if (!enabled) return fs.rmSync(AUTOSTART, { force: true });
  fs.mkdirSync(path.dirname(AUTOSTART), { recursive: true });
  fs.writeFileSync(AUTOSTART, `[Desktop Entry]
Type=Application
Name=Lanclip
Comment=Share clipboard and files on your LAN
Exec=${launcher.map(shQuote).join(' ')} --lanclip-background
X-GNOME-Autostart-enabled=true
NoDisplay=true
`);
}
const linuxAutostartEnabled = () => fs.existsSync(AUTOSTART);

module.exports = { install, uninstall, setLinuxAutostart, linuxAutostartEnabled, LABELS };
