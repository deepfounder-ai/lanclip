// Installs/removes "Copy to LAN" / "Paste from LAN" entries in the OS file manager context menus.
//   Windows: Explorer verbs in HKCU\Software\Classes (no admin needed)
//   macOS:   Finder Quick Actions (Services) in ~/Library/Services
//   Linux:   Nautilus/Caja scripts, Nemo actions, Dolphin service menu, Thunar custom actions
const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');
const { execFile } = require('child_process');

const LABELS = {
  send: 'Copy to LAN',
  paste: 'Paste from LAN',
  clip: 'Copy clipboard to LAN',
  text: 'Copy text to LAN',
};

// launcher: array of [executable, ...leadingArgs] that starts Lanclip (e.g. [electron, appPath])
async function install(launcher, { iconPath } = {}) {
  if (process.platform === 'win32') return installWindows(launcher, iconPath);
  if (process.platform === 'darwin') return installMac(launcher);
  return installLinux(launcher);
}

async function uninstall() {
  if (process.platform === 'win32') return uninstallWindows();
  if (process.platform === 'darwin') return uninstallMac();
  return uninstallLinux();
}

// ---------------------------------------------------------------- Windows
const WIN_KEYS = [
  // [registry key, label, args template]
  ['HKCU\\Software\\Classes\\*\\shell\\Lanclip.Send', LABELS.send, ['--lanclip-send', '%1']],
  ['HKCU\\Software\\Classes\\Directory\\shell\\Lanclip.Send', LABELS.send, ['--lanclip-send', '%1']],
  ['HKCU\\Software\\Classes\\Directory\\shell\\Lanclip.Paste', LABELS.paste, ['--lanclip-paste', '%1']],
  ['HKCU\\Software\\Classes\\Directory\\Background\\shell\\Lanclip.Paste', LABELS.paste, ['--lanclip-paste', '%V']],
  ['HKCU\\Software\\Classes\\Directory\\Background\\shell\\Lanclip.Clip', LABELS.clip, ['--lanclip-send-clipboard']],
];

function reg(args) {
  return new Promise((resolve, reject) => {
    execFile('reg', args, { windowsHide: true }, (err, stdout, stderr) => (err ? reject(new Error(stderr || err.message)) : resolve(stdout)));
  });
}

const winQuote = (s) => `"${s}"`;

async function installWindows(launcher, iconPath) {
  for (const [key, label, args] of WIN_KEYS) {
    const command = [...launcher, ...args].map(winQuote).join(' ');
    await reg(['add', key, '/ve', '/d', label, '/f']);
    await reg(['add', key, '/v', 'Icon', '/d', iconPath || launcher[0], '/f']);
    // Show the verb for multi-selections too (Explorer then invokes it once per file).
    await reg(['add', key, '/v', 'MultiSelectModel', '/d', 'Player', '/f']);
    await reg(['add', key + '\\command', '/ve', '/d', command, '/f']);
  }
}

async function uninstallWindows() {
  for (const [key] of WIN_KEYS) await reg(['delete', key, '/f']).catch(() => {});
}

// ---------------------------------------------------------------- shared (macOS + Linux)
const shQuote = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

// A tiny wrapper so every integration calls one stable script. It detaches so file managers
// never wait on Lanclip (the call either hands off to the running instance or becomes it).
function writeWrapper(dir, launcher) {
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, 'lanclip-cli.sh');
  fs.writeFileSync(file, `#!/bin/sh
# Generated by Lanclip. Forwards a context-menu action to the Lanclip background service.
nohup ${launcher.map(shQuote).join(' ')} "$@" >/dev/null 2>&1 &
`, { mode: 0o755 });
  fs.chmodSync(file, 0o755);
  return file;
}

function writeExecutable(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, { mode: 0o755 });
  fs.chmodSync(file, 0o755);
}

// ---------------------------------------------------------------- macOS
const MAC_SERVICES = path.join(os.homedir(), 'Library', 'Services');
const MAC_WORKFLOWS = [LABELS.send, LABELS.paste, LABELS.clip, LABELS.text];

function installMac(launcher) {
  const cli = writeWrapper(path.join(os.homedir(), 'Library', 'Application Support', 'lanclip'), launcher);
  const q = shQuote(cli);
  const finderDir = `osascript -e 'tell application "Finder" to POSIX path of (insertion location as alias)' 2>/dev/null`;

  writeWorkflow(LABELS.send, { input: 'files', script: `${q} --lanclip-send "$@"` });
  writeWorkflow(LABELS.paste, {
    input: 'files',
    script: `dir="$1"
[ -z "$dir" ] && dir=$(${finderDir})
[ -f "$dir" ] && dir=$(dirname "$dir")
[ -z "$dir" ] && dir="$HOME/Downloads"
${q} --lanclip-paste "$dir"`,
  });
  writeWorkflow(LABELS.clip, { input: 'files', script: `${q} --lanclip-send-clipboard` });
  writeWorkflow(LABELS.text, {
    input: 'text',
    script: `t=$(mktemp -t lanclip); cat > "$t"; ${q} --lanclip-send-text-file "$t"`,
  });
  // Ask the services menu to rescan.
  execFile('/System/Library/CoreServices/pbs', ['-update'], () => {});
}

function uninstallMac() {
  for (const name of MAC_WORKFLOWS) fs.rmSync(path.join(MAC_SERVICES, `${name}.workflow`), { recursive: true, force: true });
  execFile('/System/Library/CoreServices/pbs', ['-update'], () => {});
}

